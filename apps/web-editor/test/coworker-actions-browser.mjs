import assert from "node:assert/strict";
import { join } from "node:path";

// Runs within the authenticated existing browser suite. All Google I/O is
// simulated by the explicitly gated local Python fixture, not a real account.
export async function verifyActions(page, folder) {
  await page.route("https://accounts.google.com/o/oauth2/v2/auth**", async route => {
    const url = new URL(route.request().url());
    assert.equal(url.searchParams.get("code_challenge_method"), "S256");
    const callback = new URL(url.searchParams.get("redirect_uri"));
    callback.searchParams.set("state", url.searchParams.get("state"));
    callback.searchParams.set("code", "simulated-authorization-code");
    await route.fulfill({ status: 302, headers: { Location: callback.href } });
  });
  await page.getByRole("button", { name: "Email & calendar", exact: true }).click();
  const area = page.getByRole("region", { name: "Email and calendar actions", exact: true });
  const review = area.getByRole("region", { name: "Action review" });
  await area.getByRole("button", { name: "Connect Gmail", exact: true }).click();
  await area.getByRole("button", { name: "Disconnect Gmail", exact: true }).waitFor();
  assert.equal(new URL(page.url()).search, "");
  assert.equal(new URL(page.url()).pathname, "/");
  await area.getByRole("button", { name: "Connect Calendar", exact: true }).click();
  await area.getByRole("button", { name: "Disconnect Calendar", exact: true }).waitFor();
  await area.getByLabel("To", { exact: true }).fill("recipient@example.org");
  await area.getByLabel("Bcc", { exact: true }).fill("private@example.org");
  await area.getByLabel("Subject", { exact: true }).fill("প্রকল্পের অগ্রগতি");
  await area.getByLabel("Message", { exact: true }).fill("দলটি ১২টি পর্যালোচনা সম্পন্ন করেছে।\nشكراً لكم.");
  const attachment = area.getByLabel(/^report\.pdf ·/).first();
  await attachment.check();
  await area.getByRole("button", { name: "Review action", exact: true }).click();
  await review.getByRole("heading", { name: "Needs your approval" }).waitFor();
  await area.getByText("report.pdf", { exact: true }).waitFor();
  assert.match(await area.locator(".cw-action-details").innerText(), /Attachments\s+report\.pdf/);
  assert.equal(await review.getByRole("button", { name: "Approve & send email" }).isDisabled(), true);
  assert.deepEqual(await (await page.request.get("http://127.0.0.1:8000/fixture/actions/counts")).json(), { emails: 0, events: 0 });
  await area.getByText("private@example.org", { exact: true }).waitFor();
  const first = await area.locator(".cw-action-content").innerText();
  await area.getByRole("button", { name: "Edit details" }).click();
  assert.equal(await area.getByLabel("Subject", { exact: true }).inputValue(), "প্রকল্পের অগ্রগতি");
  assert.equal(await area.getByLabel(/^report\.pdf ·/).first().isChecked(), true);
  await area.getByLabel("Subject", { exact: true }).fill("অনুমোদিত প্রকল্পের অগ্রগতি");
  await area.getByRole("button", { name: "Review action", exact: true }).click();
  await review.getByRole("heading", { name: "Needs your approval" }).waitFor();
  assert.notEqual(await area.locator(".cw-action-content").innerText(), first);
  await page.locator(".workspace-coworker").evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: join(folder, "screenshots/actions-email-preview.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await review.scrollIntoViewIfNeeded();
  await page.screenshot({ path: join(folder, "screenshots/actions-approval-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1365, height: 960 });
  await review.getByRole("checkbox").check();
  await review.getByRole("button", { name: "Approve & send email" }).click();
  await review.getByText("Accepted by Gmail", { exact: true }).waitFor({ timeout: 30000 });
  await page.reload();
  await page.getByRole("button", { name: "Email & calendar", exact: true }).click();
  await area.locator(".cw-history li").filter({ hasText: "অনুমোদিত প্রকল্পের অগ্রগতি" }).getByRole("button").click();
  await review.getByText("Accepted by Gmail", { exact: true }).waitFor();
  await review.getByText("Action history", { exact: true }).click();
  await review.getByText(/execution started/).waitFor();
  assert.equal((await (await page.request.get("http://127.0.0.1:8000/fixture/actions/counts")).json()).emails, 1);
  await page.screenshot({ path: join(folder, "screenshots/actions-email-receipt.png"), fullPage: true });
  await area.getByRole("button", { name: "Prepare another action" }).click();
  await page.screenshot({ path: join(folder, "screenshots/actions-new-action-reset.png"), fullPage: true });
  const actionType = area.getByRole("combobox", { name: "Action type", exact: true });
  await actionType.waitFor();
  assert.equal(await actionType.inputValue(), "email");
  await area.getByLabel("Action type", { exact: true }).selectOption("calendar");
  await area.getByLabel("Event title", { exact: true }).fill("مراجعة المشروع");
  const day = new Date(Date.now() + 2 * 86400000).toISOString().slice(0, 10);
  await area.getByLabel("Starts", { exact: true }).fill(day + "T10:00");
  await area.getByLabel("Ends", { exact: true }).fill(day + "T11:00");
  await area.getByLabel("Time zone", { exact: true }).fill("Asia/Dhaka");
  await area.getByLabel("Guests", { exact: true }).fill("guest@example.org");
  await area.getByLabel("Event description", { exact: true }).fill("مراجعة ١٢ بنداً مع الفريق.");
  await area.getByLabel("Reminder", { exact: true }).selectOption("15");
  await area.getByRole("button", { name: "Review action", exact: true }).click();
  await review.getByRole("heading", { name: "Needs your approval" }).waitFor();
  await area.getByText(day + " 10:00:00+06:00", { exact: true }).waitFor();
  await area.getByText("15 minutes before start", { exact: true }).waitFor();
  await page.locator(".workspace-coworker").evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: join(folder, "screenshots/actions-calendar-preview.png"), fullPage: true });
  await review.getByRole("checkbox").check();
  await review.getByRole("button", { name: "Approve & create event" }).click();
  await review.getByText("Created in Google Calendar", { exact: true }).waitFor({ timeout: 30000 });
  assert.deepEqual(await (await page.request.get("http://127.0.0.1:8000/fixture/actions/counts")).json(), { emails: 1, events: 1 });
  await area.getByRole("button", { name: "Prepare another action" }).click();
  await area.getByLabel("Action type", { exact: true }).selectOption("email");
  await area.getByLabel("Subject", { exact: true }).fill("Uncertain send fixture");
  await area.getByLabel("To", { exact: true }).fill("recipient@example.org");
  await area.getByLabel("Message", { exact: true }).fill("Simulated send with a lost response.");
  await area.getByRole("button", { name: "Review action", exact: true }).click();
  await review.getByRole("heading", { name: "Needs your approval" }).waitFor();
  await page.request.post("http://127.0.0.1:8000/fixture/actions/lose-reply");
  await review.getByRole("checkbox").check();
  await review.getByRole("button", { name: "Approve & send email" }).click();
  await review.getByRole("heading", { name: "Result uncertain" }).waitFor({ timeout: 30000 });
  assert.equal(await review.getByRole("button", { name: "Approve & send email" }).count(), 0);
  await page.screenshot({ path: join(folder, "screenshots/actions-uncertain-result.png"), fullPage: true });
  assert.equal((await (await page.request.get("http://127.0.0.1:8000/fixture/actions/counts")).json()).emails, 2);
  page.once("dialog", dialog => dialog.accept());
  await area.getByRole("button", { name: "Disconnect Gmail", exact: true }).click();
  await area.getByRole("button", { name: "Connect Gmail", exact: true }).waitFor();
  await page.getByRole("button", { name: "Drafts & files", exact: true }).click();
}
